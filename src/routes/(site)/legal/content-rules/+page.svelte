<h1>Content rules</h1>
<p><em>Last updated 11 November 2026.</em></p>
<p>
	Moderators use these rules to review every new project, and to handle reports. Breaking them gets
	content withheld or removed; serious or repeated breaks get accounts suspended.
</p>

<h2>Projects must be</h2>
<ul>
	<li>
		<strong>What they say they are.</strong> A shader pack has a <code>shaders/</code> folder, a
		texture or data pack has <code>pack.mcmeta</code>, a mod has a loader manifest. The site checks
		this when you upload.
	</li>
	<li>
		<strong>Yours to share.</strong> No reuploads of other people’s work, even if it’s free elsewhere,
		unless its licence allows it and you say who made it.
	</li>
	<li>
		<strong>Described honestly.</strong> A summary and description that say what the project does, which
		versions and loaders it supports, and what it needs.
	</li>
	<li>
		<strong>Free.</strong> No paywalls, no “unlock the full version” links, no forced ads or link shorteners
		in front of downloads.
	</li>
</ul>

<h2>Never allowed</h2>
<ul>
	<li>
		Malware, or anything that downloads, runs or hides code the description doesn’t mention:
		stealers, miners, remote access, account grabbers. Uploads are virus-scanned; files the scanner
		can’t clear wait for a moderator.
	</li>
	<li>Obfuscated code in mods without a clear, stated reason.</li>
	<li>Hateful, sexual or violent content, harassment, or content aimed at a real person.</li>
	<li>
		Anything illegal, including content that breaks the Minecraft EULA or Mojang’s usage guidelines.
	</li>
	<li>
		Spam: duplicate projects, keyword stuffing, or projects that only advertise something else.
	</li>
</ul>

<h2>Screenshots and descriptions</h2>
<ul>
	<li>Screenshots should show the project itself, at the settings you name.</li>
	<li>
		Descriptions may link to your source code, issue tracker, wiki and Discord. Images in
		descriptions come from your gallery.
	</li>
</ul>

<h2>Reviews</h2>
<p>
	Review the project, not the person. No reviews of your own projects, no review trading, no private
	information.
</p>

<h2>If your project is withheld or rejected</h2>
<p>
	You’ll get a notification with the moderator’s reason. Fix the problem and submit again from your
	dashboard.
</p>
